#!/usr/bin/env python3
"""Embed a self-contained asset into a C header.

The Jeopardy webpage has no external resources (no CDN, no fonts, no scripts
from the network). This script turns assets/index.html into a byte-exact C
string so the service binary stays self-contained.
"""
from __future__ import annotations

import argparse
import os


def embed(source: str, output: str, symbol: str = "JPQ_WEB_HTML") -> None:
    with open(source, "rb") as f:
        data = f.read()
    with open(output, "w", encoding="ascii") as f:
        f.write("/* generated by tools/embed_assets.py -- do not edit */\n")
        f.write("#define JPQ_WEB_ASSET_INCLUDED 1\n")
        f.write(f"static const char {symbol}[] =\n")
        f.write('"')
        col = 0
        for byte in data:
            f.write("\\%03o" % byte)
            col += 4
            if col >= 80:
                f.write('"\n"')
                col = 0
        f.write('";\n')
        f.write(f"#define {symbol}_LEN (unsigned)(sizeof({symbol}) - 1u)\n")
    print(f"embed: {source} -> {output} ({len(data)} bytes)")


def main() -> int:
    ap = argparse.ArgumentParser(description="Embed a web asset into a C header")
    ap.add_argument("--source", required=True)
    ap.add_argument("--output", required=True)
    ap.add_argument("--symbol", default="JPQ_WEB_HTML")
    args = ap.parse_args()
    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    embed(args.source, args.output, args.symbol)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
