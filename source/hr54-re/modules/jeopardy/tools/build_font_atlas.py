#!/usr/bin/env python3
"""Bake packed 8-bit alpha font atlases for the native Jeopardy renderer.

Source font is Overpass (SIL Open Font License, see assets/OFL.txt) from the
shared hr54-ui assets. The receiver never loads a font at runtime: this host
tool pre-rasterises grayscale coverage masks into a committed C header. Pillow
is a host-only dependency, exactly like the native-ui icon baker.

Atlas layout: tightly packed 8-bit alpha, row-major, top row first. Each glyph
records the pen bearing (bitmap top-left relative to the baseline origin) and
the advance width, so the renderer only needs nearest-neighbour blitting.
"""
import argparse
from pathlib import Path
from PIL import ImageFont

FIRST, LAST = 32, 126


def pack(path, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    line = ascent + descent
    items = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        mask, off = font.getmask2(ch, mode="L")
        w, h = mask.size
        advance = int(round(font.getlength(ch)))
        items.append({
            "code": code, "w": w, "h": h, "bx": int(off[0]),
            "by": int(off[1]) - ascent, "adv": advance,
            "bits": bytes(mask) if w and h else b"",
        })
    # Shelf packing: widest glyphs first keeps rows tight for Latin text.
    order = sorted(range(len(items)), key=lambda i: (-items[i]["w"], items[i]["code"]))
    width = 512
    x = y = rowh = 0
    placed = {}
    for i in order:
        it = items[i]
        if x + it["w"] > width:
            x = 0
            y += rowh + 1
            rowh = 0
        placed[i] = (x, y)
        it["px"], it["py"] = x, y
        x += it["w"] + 1
        rowh = max(rowh, it["h"])
    height = y + rowh
    canvas = bytearray(width * height)
    for i, it in enumerate(items):
        px, py = placed[i]
        for gy in range(it["h"]):
            src = gy * it["w"]
            dst = (py + gy) * width + px
            canvas[dst:dst + it["w"]] = it["bits"][src:src + it["w"]]
    return width, height, ascent, line, items


def emit(out, name, path, size):
    width, height, ascent, line, items = pack(path, size)
    out.append(f"/* {name}: Overpass {size}px, {width}x{height}, ascent {ascent}, line {line}. */")
    bits = list(items)
    # Emit packed bytes as a C array.
    pixels = bytearray(width * height)
    for it in bits:
        for gy in range(it["h"]):
            src = gy * it["w"]
            dst = (it["py"] + gy) * width + it["px"]
            pixels[dst:dst + it["w"]] = it["bits"][src:src + it["w"]]
    out.append(f"static const unsigned char {name}_bits[{len(pixels)}]={{")
    for i in range(0, len(pixels), 32):
        out.append(",".join(str(b) for b in pixels[i:i + 32]) + ",")
    out.append("};")
    out.append(f"static const JpqGlyph {name}_glyphs[{len(items)}]={{")
    for it in items:
        out.append("{%d,%d,%d,%d,%d,%d,%d}," % (it["px"], it["py"], it["w"], it["h"], it["bx"], it["by"], it["adv"]))
    out.append("};")
    out.append(f"const JpqFontAtlas {name}={{{name}_bits,{width},{height},{ascent},{line},{name}_glyphs,{len(items)},{FIRST}}};")
    out.append("")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--font", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    args = ap.parse_args()
    out = [
        "/* Generated by tools/build_font_atlas.py. Do not edit. Overpass, OFL-1.1. */",
        "#ifndef JPQ_FONT_DATA_H",
        "#define JPQ_FONT_DATA_H",
        '#include "jpq_font.h"',
        "",
    ]
    emit(out, "jpq_font_body", args.font, 20)
    emit(out, "jpq_font_title", args.font, 34)
    # A third, smaller atlas lets long category words and dense clue text shrink
    # instead of being split or overlapped.
    emit(out, "jpq_font_small", args.font, 14)
    # A 12px help/category atlas: the longest real category words (e.g.
    # INTERNATIONAL) stay whole inside a board column and the board hint line
    # fits without colliding with the podium row.
    emit(out, "jpq_font_tiny", args.font, 12)
    out.append("#endif")
    args.out.write_text("\n".join(out) + "\n")
    print("atlas:", args.out, args.out.stat().st_size, "bytes")


if __name__ == "__main__":
    main()
